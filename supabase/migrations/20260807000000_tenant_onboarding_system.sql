CREATE OR REPLACE FUNCTION update_onboarding_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_onboarding_profiles_updated_at
  BEFORE UPDATE ON tenant_onboarding_profiles
  FOR EACH ROW EXECUTE FUNCTION update_onboarding_updated_at();

