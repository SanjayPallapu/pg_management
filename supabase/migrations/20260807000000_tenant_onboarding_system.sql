  ON tenant_onboarding_profiles FOR ALL
  USING (owner_id = auth.uid())
  WITH CHECK (owner_id = auth.uid());

CREATE POLICY "owners_manage_onboarding_links"
  ON tenant_onboarding_links FOR ALL
  USING (owner_id = auth.uid())
  WITH CHECK (owner_id = auth.uid());

CREATE POLICY "owners_manage_onboarding_documents"
  ON tenant_onboarding_documents FOR ALL
  USING (
    onboarding_profile_id IN (
      SELECT id FROM tenant_onboarding_profiles WHERE owner_id = auth.uid()
    )
  )
  WITH CHECK (
    onboarding_profile_id IN (
      SELECT id FROM tenant_onboarding_profiles WHERE owner_id = auth.uid()
    )
  );

