-- ============================================================================
-- Tenant Onboarding System - New Tables (Isolated Module)
-- Does NOT modify existing tables, relationships, or migrations.
-- All onboarding data lives in dedicated tables with FK references to tenants.
-- ============================================================================

-- Enable crypto extension for gen_random_uuid() if not already enabled
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ==========================================================================
-- 1. tenant_onboarding_profiles
--    Stores the full onboarding profile data for a tenant.
--    One row per tenant. Created when onboarding is initiated.
-- ==========================================================================
CREATE TABLE IF NOT EXISTS tenant_onboarding_profiles (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  pg_id           UUID NOT NULL REFERENCES pgs(id) ON DELETE CASCADE,
  owner_id        UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,

  -- Onboarding status
  status          TEXT NOT NULL DEFAULT 'not_started'
                  CHECK (status IN ('not_started','link_sent','link_viewed','form_started','form_submitted','profile_completed','pending_verification','verified','rejected')),

  -- Verification status (separate from onboarding flow status)
  verification_status TEXT NOT NULL DEFAULT 'pending'
                  CHECK (verification_status IN ('pending','verified','rejected','re_upload_requested')),

  -- Personal Information
  full_name           TEXT,
  date_of_birth       DATE,
  gender              TEXT,
  blood_group         TEXT,
  emergency_contact_name  TEXT,
  emergency_contact_phone TEXT,

  -- Identity Verification
  id_proof_type       TEXT,
  id_proof_number     TEXT,
  id_proof_url        TEXT,
  address_proof_url   TEXT,

  -- Contact Details
  email               TEXT,
  alternate_phone     TEXT,
  permanent_address   TEXT,

  -- Occupation
  occupation          TEXT,
  company_name         TEXT,
  office_address       TEXT,

  -- Stay Details
  stay_purpose        TEXT,
  expected_stay_duration TEXT,
  move_in_date        DATE,

  -- Payment Details
  payment_mode        TEXT,
  upi_id              TEXT,
  bank_account_number TEXT,
  ifsc_code           TEXT,
  bank_name           TEXT,

  -- Food Preferences
  food_preference     TEXT,
  dietary_restrictions TEXT,

  -- PG Rules & Agreement
  rules_acknowledged  BOOLEAN DEFAULT FALSE,
  agreement_accepted  BOOLEAN DEFAULT FALSE,
  agreement_signed_at TIMESTAMPTZ,

  -- Auto-save support
  form_progress       INTEGER DEFAULT 0,  -- 0-100 percentage
  last_saved_step     TEXT,

  -- Metadata
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at    TIMESTAMPTZ,
  verified_at     TIMESTAMPTZ,
  verified_by     UUID REFERENCES auth.users(id),

  UNIQUE(tenant_id)
);

-- Index for quick lookup by tenant
CREATE INDEX IF NOT EXISTS idx_onboarding_profiles_tenant_id ON tenant_onboarding_profiles(tenant_id);
CREATE INDEX IF NOT EXISTS idx_onboarding_profiles_pg_id ON tenant_onboarding_profiles(pg_id);
CREATE INDEX IF NOT EXISTS idx_onboarding_profiles_status ON tenant_onboarding_profiles(status);

-- ==========================================================================
-- 2. tenant_onboarding_links
--    Secure onboarding links generated by the owner.
--    Contains a unique token for public access.
-- ==========================================================================
CREATE TABLE IF NOT EXISTS tenant_onboarding_links (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  pg_id           UUID NOT NULL REFERENCES pgs(id) ON DELETE CASCADE,
  owner_id        UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  token           TEXT NOT NULL UNIQUE DEFAULT encode(gen_random_bytes(32), 'hex'),

  -- Link status tracking
  status          TEXT NOT NULL DEFAULT 'sent'
                  CHECK (status IN ('sent','viewed','started','submitted','completed','expired','revoked')),

  -- Communication tracking
  sent_via        TEXT,
  sent_at         TIMESTAMPTZ,
  viewed_at       TIMESTAMPTZ,
  started_at      TIMESTAMPTZ,
  submitted_at    TIMESTAMPTZ,
  completed_at    TIMESTAMPTZ,

  -- Expiry (default 7 days)
  expires_at      TIMESTAMPTZ DEFAULT (now() + interval '7 days'),

  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_onboarding_links_token ON tenant_onboarding_links(token);
CREATE INDEX IF NOT EXISTS idx_onboarding_links_tenant_id ON tenant_onboarding_links(tenant_id);

-- ==========================================================================
-- 3. tenant_onboarding_documents
--    Documents uploaded by the tenant during onboarding.
-- ==========================================================================
CREATE TABLE IF NOT EXISTS tenant_onboarding_documents (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  onboarding_profile_id UUID NOT NULL REFERENCES tenant_onboarding_profiles(id) ON DELETE CASCADE,
  tenant_id       UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,

  document_type   TEXT NOT NULL,
  document_name   TEXT,
  file_url        TEXT NOT NULL,
  file_size       BIGINT,
  mime_type       TEXT,

  -- Verification status per document
  status          TEXT NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending','approved','rejected','re_upload_requested')),
  rejection_reason TEXT,

  uploaded_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at     TIMESTAMPTZ,
  reviewed_by     UUID REFERENCES auth.users(id)
);

CREATE INDEX IF NOT EXISTS idx_onboarding_documents_profile_id ON tenant_onboarding_documents(onboarding_profile_id);
CREATE INDEX IF NOT EXISTS idx_onboarding_documents_tenant_id ON tenant_onboarding_documents(tenant_id);

-- ==========================================================================
-- 4. tenant_onboarding_timeline
--    Complete activity timeline for the onboarding process.
-- ==========================================================================
CREATE TABLE IF NOT EXISTS tenant_onboarding_timeline (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  pg_id           UUID NOT NULL REFERENCES pgs(id) ON DELETE CASCADE,
  onboarding_profile_id UUID REFERENCES tenant_onboarding_profiles(id) ON DELETE SET NULL,

  event_type      TEXT NOT NULL,
  event_description TEXT,
  event_metadata  JSONB DEFAULT '{}'::jsonb,

  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
