CREATE INDEX IF NOT EXISTS idx_onboarding_timeline_tenant_id ON tenant_onboarding_timeline(tenant_id);
CREATE INDEX IF NOT EXISTS idx_onboarding_timeline_pg_id ON tenant_onboarding_timeline(pg_id);
CREATE INDEX IF NOT EXISTS idx_onboarding_timeline_created_at ON tenant_onboarding_timeline(created_at DESC);

